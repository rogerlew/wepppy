"""Controlled R02 sample-support evidence using pinned real predictors.

This synthetic ten-row climate is a boundary test, not authentic Climate/NOAA
acceptance. Its CSV is generated by the unchanged Climate-owned exporter.
"""
import argparse
import json
import logging
from pathlib import Path
from types import SimpleNamespace

import pandas as pd

from wepppy.nodb.core.climate_artifact_export_service import ClimateArtifactExportService
from wepppy.nodb.mods.postfire_debris_flow.rainfall_io import digest
from wepppy.nodb.mods.postfire_debris_flow.results import (
    RainfallInputs, build_m1_results, open_results, list_events)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    here = Path(__file__).resolve().parent
    inventory = json.loads((here/'source_inventory.json').read_text())
    predictor = here.parents[1]/'20260909_staley_m1_predictors/artifacts/generated/wallow-rebuilt-final/bundle/manifest.json'
    args.output.mkdir(mode=0o700)
    source = args.output/'controlled.parquet'
    pd.DataFrame({'prcp':[1.]*10, 'year':list(range(1,11)), 'month':[1]*10,
                  'day_of_month':[1]*10, 'peak_intensity_15':[40.]+[0.]*9,
                  'peak_intensity_30':[40.]*10, 'peak_intensity_60':[0.]*10}).to_parquet(source,index=False)
    climate = SimpleNamespace(logger=logging.getLogger('controlled-r02'),runid='controlled-r02',
                              climatestation='controlled',watershed_instance=SimpleNamespace(centroid=(-109.,33.)))
    csv = ClimateArtifactExportService().export_cli_precip_frequency_csv(climate,source)
    assert csv is not None
    inputs = RainfallInputs(predictor,source,
        {str(predictor):inventory['predictor_manifest_sha256'],str(source.absolute()):digest(source),
         str(csv.absolute()):digest(csv)},'controlled-R02','synthetic boundary fixture','simulation_labels',
        'Pinned Wallow predictors; controlled rainfall, not authentic event evidence',cli_frequency_csv=csv)
    output = args.output/'bundle'
    manifest = build_m1_results(inputs,output,frequency_source='cli',return_intervals=[1,2,5,10],
                               durations=[15,30,60],target_probabilities=[.5,.75])
    catalog = open_results(output,expected_manifest_sha256=digest(output/'manifest.json'))
    design = pd.read_parquet(output/'design.parquet')
    unsupported = design[(design.duration_minutes==15)&(design.return_interval_years<10)]
    assert list(unsupported.rank_index)==[9,4,1]
    assert set(unsupported.reason)=={'insufficient_positive_samples'}
    assert unsupported[['rainfall_mm','intensity_mm_per_hour','probability']].isna().all().all()
    assert set(design[design.duration_minutes==30].status)=={'available'}
    assert set(design[design.duration_minutes==60].reason)=={'no_positive_samples'}
    assert list_events(catalog,duration_minutes=15)['total']==10
    report = {'source_kind':'controlled synthetic rainfall / genuine pinned predictors',
              'policy':'R02 unavailable unsupported rank', 'csv_exporter':'unchanged ClimateArtifactExportService',
              'sources_sha256':manifest['sources_sha256'], 'manifest_sha256':digest(output/'manifest.json'),
              'design':json.loads(design.to_json(orient='records')), 'tables':manifest['tables']}
    (args.output/'acceptance.json').write_text(json.dumps(report,indent=2,allow_nan=False)+'\n')
    print(json.dumps({'unsupported_scenarios':len(unsupported),'tables':manifest['tables']}))


if __name__ == '__main__':
    main()
