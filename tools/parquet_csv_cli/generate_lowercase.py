"""Regenerate native simple-lowercase mappings from the pinned filter oracle."""
from pathlib import Path
import duckdb

if duckdb.__version__ != '1.1.1':
    raise RuntimeError('The compatibility oracle must be DuckDB 1.1.1')
scalars = ''.join(chr(i) for i in range(0x110000) if not 0xD800 <= i <= 0xDFFF)
lowered = duckdb.connect().execute('SELECT lower(?)', [scalars]).fetchone()[0]
if len(lowered) != len(scalars):
    raise RuntimeError('Oracle is not a scalar-to-scalar lowercase mapping')
pairs = [(ord(a), ord(b)) for a, b in zip(scalars, lowered) if a != b and ord(a) > 127]
text = '''// Generated by tools/parquet_csv_cli/generate_lowercase.py using DuckDB 1.1.1.
// Freeze legacy filter semantics rather than inheriting Rust Unicode upgrades.
pub fn lower(c: char) -> char {
    if c.is_ascii() { return c.to_ascii_lowercase(); }
    match PAIRS.binary_search_by_key(&(c as u32), |pair| pair.0) {
        Ok(index) => char::from_u32(PAIRS[index].1).unwrap(),
        Err(_) => c,
    }
}
const PAIRS: &[(u32, u32)] = &[\n'''
text += ''.join(f'    (0x{a:X}, 0x{b:X}),\n' for a, b in pairs)
text += '];\n'
(Path(__file__).resolve().parent / 'rust/src/lowercase.rs').write_text(text)
print(f'Generated {len(pairs)} non-ASCII mappings from DuckDB {duckdb.__version__}')
